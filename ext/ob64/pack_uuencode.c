/* Encodes slen bytes, chars only; returns the char count */
static size_t
uu_encode_raw(const uint8_t *s, size_t slen, uint8_t *o)
{
    uint8_t *start = o;

#if PACK_WORDSIZE == 64
    /* 64-bit inner loop: reads 8 bytes, consumes 6, produces 8 */
    while (slen >= 8) {
        pack_enc_loop_64_inner(&s, &o, uu_enc_12bit);
        slen -= 6;
    }
#endif

    /* 32-bit inner loop: reads 4 bytes, consumes 3, produces 4 */
    while (slen >= 4) {
        pack_enc_loop_32_inner(&s, &o, uu_enc_12bit);
        slen -= 3;
    }

    /* Scalar tail: 1-3 remaining bytes */
    if (slen == 3) {
        *o++ = uu_enc_6bit[  s[0] >> 2];
        *o++ = uu_enc_6bit[((s[0] << 4) | (s[1] >> 4)) & 0x3F];
        *o++ = uu_enc_6bit[((s[1] << 2) | (s[2] >> 6)) & 0x3F];
        *o++ = uu_enc_6bit[  s[2] & 0x3F];
    }
    else if (slen == 2) {
        *o++ = uu_enc_6bit[  s[0] >> 2];
        *o++ = uu_enc_6bit[((s[0] << 4) | (s[1] >> 4)) & 0x3F];
        *o++ = uu_enc_6bit[ (s[1] << 2) & 0x3F];
        *o++ = uu_enc_6bit[0];  /* padding */
    }
    else if (slen == 1) {
        *o++ = uu_enc_6bit[  s[0] >> 2];
        *o++ = uu_enc_6bit[ (s[0] << 4) & 0x3F];
        *o++ = uu_enc_6bit[0];  /* padding */
        *o++ = uu_enc_6bit[0];  /* padding */
    }

    return (size_t)(o - start);
}

